function normalizePlayerName(value: string) {
  return value.toLowerCase().replace(/[^a-z0-9]/g, "");
}

export function getWorldsPlayerRanking(role: ProRole, displayName: string) {
  const rankings = WORLDS_PLAYER_RANKINGS[role];
  const fieldSize: number = rankings.length;
  const normalizedName = normalizePlayerName(displayName);
  const index = rankings.findIndex((name) => normalizePlayerName(name) === normalizedName);
  if (index === -1) return null;
  return {
    rank: index + 1,
    fieldSize,
    percentile: fieldSize === 1 ? 0.5 : 1 - index / (fieldSize - 1),
  };
}
